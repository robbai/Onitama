int evaluate_white(Board *board) {
    int eval = 0;

    // Iterate through pieces.
    Bitboard pieces = board->pieces[WHITE][STUDENT] | board->pieces[WHITE][MASTER];
    while (pieces) {
        int sq = __builtin_ctz(pieces);
        Bitboard mask = (1u << sq);

        // Add material.
        bool master = (board->pieces[WHITE][MASTER] & mask);
        if (!master)
            eval += MATERIAL;

        // Iterate through cards.
        for (Card card : board->cards[WHITE]) {
            int index =
                    ((sq * CARD_NUM + card) * PIECE_TYPES_NUM + master) * PLAYERS_NUM +
                    board->turn;
            eval += PARAMETERS[index];
        }

        pieces ^= mask;
    }

    return eval;
}

int evaluate_black(Board *board) {
    int eval = 0;

    // Iterate through pieces.
    Bitboard pieces = board->pieces[BLACK][STUDENT] | board->pieces[BLACK][MASTER];
    while (pieces) {
        int sq = __builtin_ctz(pieces);
        Bitboard mask = (1u << sq);

        // Add material.
        bool master = (board->pieces[BLACK][MASTER] & mask);
        if (!master)
            eval += MATERIAL;

        // Iterate through cards.
        for (Card card : board->cards[BLACK]) {
            int index = (((SQUARE_NUM - 1 - sq) * CARD_NUM + card) * PIECE_TYPES_NUM +
                         master) *
                                PLAYERS_NUM +
                        (1 - board->turn);
            eval += PARAMETERS[index];
        }

        pieces ^= mask;
    }

    return eval;
}

int evaluate(Board *board) {
    return evaluate_white(board) - evaluate_black(board);
}

void get_evaluation_parameters(int *parameters) {
    std::copy(std::begin(PARAMETERS), std::end(PARAMETERS), parameters);
}

void set_evaluation_parameters(int *parameters) {
    std::copy(parameters, parameters + TOTAL_PARAMETERS, PARAMETERS);
}

bool is_parameter_used(Board *board, int p) {
    bool turn = p % PLAYERS_NUM;
    bool master = (p / PLAYERS_NUM) % PIECE_TYPES_NUM;
    Card card = (Card)((p / (PLAYERS_NUM * PIECE_TYPES_NUM)) % CARD_NUM);
    uint8_t sq = (p / (PLAYERS_NUM * PIECE_TYPES_NUM * CARD_NUM)) % SQUARE_NUM;

    bool side = turn != board->turn;

    if (board->cards[side][0] != card && board->cards[side][1] != card)
        return false;

    if (side) {
        return side && board->pieces[BLACK][master] & (1u << (SQUARE_NUM - 1 - sq));
    } else {
        return !side && board->pieces[WHITE][master] & (1u << sq);
    }
}
