int evaluate_white(Board *board, bool phase) {
    int eval = 0;

    // Iterate through pieces.
    Bitboard pieces = board->pieces[WHITE][STUDENT] | board->pieces[WHITE][MASTER];
    while (pieces) {
        int sq = __builtin_ctz(pieces);
        Bitboard mask = (1u << sq);

        // Add material.
        eval += MATERIAL;

        // Iterate through cards.
        bool master = (board->pieces[WHITE][MASTER] & mask);
        for (Card card : board->cards[WHITE]) {
            int index =
                    (((sq * CARD_NUM + card) * PIECE_TYPES_NUM + master) * PLAYERS_NUM +
                     board->turn) *
                            2 +
                    phase;
            eval += PARAMETERS[index];
        }

        pieces ^= mask;
    }

    return eval;
}

int evaluate_black(Board *board, bool phase) {
    int eval = 0;

    // Iterate through pieces.
    Bitboard pieces = board->pieces[BLACK][STUDENT] | board->pieces[BLACK][MASTER];
    while (pieces) {
        int sq = __builtin_ctz(pieces);
        Bitboard mask = (1u << sq);

        // Add material.
        eval += MATERIAL;

        // Iterate through cards.
        bool master = (board->pieces[BLACK][MASTER] & mask);
        for (Card card : board->cards[BLACK]) {
            int index = ((((SQUARE_NUM - 1 - sq) * CARD_NUM + card) * PIECE_TYPES_NUM +
                          master) *
                                 PLAYERS_NUM +
                         (1 - board->turn)) *
                                2 +
                        phase;
            eval += PARAMETERS[index];
        }

        pieces ^= mask;
    }

    return eval;
}

int evaluate(Board *board) {
    float phase = __builtin_popcount(board->pieces[WHITE][STUDENT] |
                                     board->pieces[BLACK][STUDENT]);
    phase /= 8;

    int phase1 = evaluate_white(board, false) - evaluate_black(board, false);
    phase1 *= 10 * phase;
    int phase2 = evaluate_white(board, true) - evaluate_black(board, true);
    phase2 *= 10 * (1 - phase);

    return phase1 + phase2;
}

int to_centi(int evaluation) {
    return evaluation / 10;
}
